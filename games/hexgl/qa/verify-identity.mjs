  evidence.renderer=await page.evaluate(()=>{const gl=hexGL.canvas.getContext('webgl');const ext=gl.getExtension('WEBGL_debug_renderer_info');return gl.getParameter(ext.UNMASKED_RENDERER_WEBGL);});
